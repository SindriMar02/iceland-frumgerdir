/**
 * Nýpugarðar — export every visible and published string for proofreading.
 *
 *   node --experimental-strip-types tools/nypugardar-copy-export.mjs [out.md]
 *
 * Generated from the source, never retyped, so nothing is missed and every
 * fix maps straight back to a key path: copy.ts (EN and IS side by side),
 * the labels in data.ts, and what tools/nypugardar-seo.mjs publishes (titles,
 * meta descriptions, JSON-LD descriptions, the FAQ mirror, llms.txt). Guest
 * reviews are listed separately and marked NOT TO BE EDITED.
 */
import { readFileSync, writeFileSync } from 'node:fs'

const { COPY } = await import('../src/preview/nypugardar/copy.ts')
/* data.ts imports './photos' without an extension, which Node's type stripping
 * will not resolve, so its strings are read from the source text instead. */
const dataSrc = readFileSync(new URL('../src/preview/nypugardar/data.ts', import.meta.url), 'utf8')
const unq = (s) => s.replace(/\\n/g, '\n').replace(/\\'/g, "'")
const out = process.argv[2] || '../_docs/NYPUGARDAR-COPY-FOR-PROOFREAD.md'

const esc = (v) => String(v).replace(/\|/g, '\\|').replace(/\n/g, '<br>')
const rows = []
function walk(en, is, path) {
  if (typeof en === 'string') return rows.push([path, en, is])
  if (Array.isArray(en)) return en.forEach((v, i) => walk(v, is?.[i], `${path}[${i}]`))
  for (const k of Object.keys(en)) walk(en[k], is?.[k], path ? `${path}.${k}` : k)
}
walk(COPY.en, COPY.is, '')

const groups = new Map()
for (const r of rows) {
  const g = r[0].split(/[.[]/)[0]
  if (!groups.has(g)) groups.set(g, [])
  groups.get(g).push(r)
}

let md = `# Nýpugarðar: all copy, for proofreading

Generated ${new Date().toISOString().slice(0, 10)} by \`iceland-redesigns/tools/nypugardar-copy-export.mjs\` from the source files. Do not edit this file; send fixes back.

## Instructions for the proofreader

- Write natural, native Icelandic and plain British English. It should read as if the owner, Bogga, wrote it herself: warm, simple, first person plural ("we", "við"), short sentences.
- No em or en dashes in prose. Time and number ranges like 16:00–23:30 are fine. No AI-sounding phrasing ("nestled", "boasts", "unforgettable", "hidden gem", "whether you are…").
- **Do not change facts, numbers or names.** If a fact looks wrong or odd, flag it instead of fixing it.
- Guest reviews at the end are quotations. **Do not edit them.**
- FAQ answers exist twice: in \`copy.ts\` (faq.items) and in \`tools/nypugardar-seo.mjs\` (FAQ_EN / FAQ_IS). They must stay byte-identical or the build fails. A fix to one is a fix to both.
- Return fixes as: \`key path → new EN / new IS\`. They get applied to \`src/preview/nypugardar/copy.ts\`, then \`npx tsc -b\` and \`npm run build:nypugardar\` are rerun.

## 1. Page copy (\`src/preview/nypugardar/copy.ts\`)
`
for (const [g, rs] of groups) {
  md += `\n### ${g}\n\n| Key | English | Íslenska |\n|---|---|---|\n`
  for (const [p, en, is] of rs) md += `| \`${p}\` | ${esc(en)} | ${esc(is ?? '')} |\n`
}

md += `\n## 2. Labels in \`data.ts\` (English fallbacks; the page renders the copy.ts keys)\n\n| Const | Label |\n|---|---|\n`
for (const m of dataSrc.matchAll(/(?:label|rule|note|tail): '([^']+)'/g)) md += `| | ${esc(m[1])} |\n`
const foot = dataSrc.match(/export const FOOTNOTE =\s*'([^']+)'/)
if (foot) md += `| \`FOOTNOTE\` | ${esc(foot[1])} |\n`

const seo = readFileSync(new URL('./nypugardar-seo.mjs', import.meta.url), 'utf8')
const pick = (re) => [...seo.matchAll(re)].map((m) => m[1])
md += `\n## 3. Published by \`tools/nypugardar-seo.mjs\`\n\n### Titles and meta descriptions\n\n`
for (const t of pick(/title: '([^']+)'/g)) md += `- title: ${t}\n`
for (const d of pick(/desc: `([^`]+)`/g)) md += `- description: ${d}\n`
md += `\n### JSON-LD descriptions\n\n`
for (const d of pick(/\? '([^']{60,})'\n/g).concat(pick(/: '(Kyrrlátt, fjölskyldurekið[^']+)'/g))) md += `- ${d}\n`
md += `\n### FAQ mirror (must match copy.ts faq.items exactly)\n\n`
for (const [q, a] of [...seo.matchAll(/\['([^']+)', '([^']+)'\]/g)].map((m) => [m[1], m[2]])) md += `- **${q}** ${a}\n`
const llms = seo.match(/const txt = `([\s\S]*?)`\n/)
if (llms) md += `\n### llms.txt (template; \${...} are filled at build time)\n\n\`\`\`\n${llms[1]}\n\`\`\`\n`

md += `\n## 4. Guest reviews: NOT TO BE EDITED (verbatim quotations from Booking.com)\n\n`
for (const m of dataSrc.matchAll(/text: '((?:[^'\\]|\\.)*)',\s*name: '([^']+)',\s*place: '([^']+)'(?:,\s*date: '([^']+)')?/g))
  md += `- "${esc(unq(m[1]))}" (${m[2]}, ${m[3]}${m[4] ? ', ' + m[4] : ''})\n`

writeFileSync(out, md)
console.log(`nypugardar-copy-export: ${rows.length} copy keys → ${out}`)
