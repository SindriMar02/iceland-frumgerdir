/* Build-time generator for the Naustið handwriting + display type.
 *
 * The reference (haven-annecy.fr) parses a .ttf with opentype.js in the browser
 * on every visit to build its self-writing script. We do the same work once,
 * here, and ship the result as data: no font parser in the bundle, no
 * font-load race, and the per-letter timings are identical on every device.
 *
 *   python3 _scratch/hw-extract.py  → glyph outlines as SVG path data
 *   headless Chrome                 → path.getTotalLength() per glyph (exact)
 *   →  src/preview/naustid/handwriting.ts
 *
 * Run:  node scripts/naustid-handwriting.mjs
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import puppeteer from 'puppeteer-core'

const HOME = process.env.HOME
const EXTRACT = path.resolve(process.cwd(), 'scripts/hw-extract.py')
const SCRIPT_FONT = `${HOME}/Design fonts/Arkipelago/Arkipelago.otf`
const DISPLAY_FONT = `${HOME}/Design fonts/Valley Sans/ttf/ValleySans-ExtraBold.ttf`

/* The five handwritten lines, keyed the way the page refers to them. */
const SCRIPT_STRINGS = {
  mark: 'Naustið',                 // the wordmark — drawn once, never animated
  amma: 'eins og heima hjá ömmu',  // §3, inside the moss panel
  alla: 'alla daga',               // §4, over MATSEÐILL
  sidan: 'síðan 1930',             // §6, over HÚSIÐ
  sjaumst: 'sjáumst',              // footer
}

/* The two flat display words that the script overlaps. */
const DISPLAY_STRINGS = { matsedill: 'MATSEÐILL', husid: 'HÚSIÐ' }

const run = (font, strings) =>
  JSON.parse(execFileSync('python3', [EXTRACT, font, ...Object.values(strings)],
    { encoding: 'utf8', maxBuffer: 1e8 }))

const scriptRaw = run(SCRIPT_FONT, SCRIPT_STRINGS)
const displayRaw = run(DISPLAY_FONT, DISPLAY_STRINGS)

/* Exact path lengths — only a real SVG engine gets these right. */
const browser = await puppeteer.launch({
  executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
  headless: 'new',
})
const page = await browser.newPage()
await page.setContent('<svg id="s" xmlns="http://www.w3.org/2000/svg"></svg>')
const measure = async (ds) =>
  page.evaluate((ds) => {
    const svg = document.getElementById('s')
    return ds.map((d) => {
      const p = document.createElementNS('http://www.w3.org/2000/svg', 'path')
      p.setAttribute('d', d)
      svg.appendChild(p)
      const l = p.getTotalLength()
      p.remove()
      return Math.round(l * 100) / 100
    })
  }, ds)

const script = {}
for (const [key, text] of Object.entries(SCRIPT_STRINGS)) {
  const raw = scriptRaw[text]
  const words = []
  for (const w of raw.words) {
    const lens = await measure(w.glyphs.map((g) => g.d))
    words.push({ width: w.width, glyphs: w.glyphs.map((g, i) => ({ d: g.d, len: lens[i] })) })
  }
  script[key] = { text, bbox: raw.bbox, words }
}

const display = {}
for (const [key, text] of Object.entries(DISPLAY_STRINGS)) {
  const raw = displayRaw[text]
  display[key] = {
    text,
    bbox: raw.bbox,
    d: raw.words.flatMap((w) => w.glyphs.map((g) => g.d)).join(' '),
  }
}

await browser.close()

const header = `/* GENERATED by scripts/naustid-handwriting.mjs — do not edit by hand.
 *
 * Script face:  Arkipelago (Nasir Udin, 2018) — free for personal and commercial use.
 * Display face: Valley Sans ExtraBold (Helsinki Type Studio, OFL).
 *
 * Coordinates are in a 1em = 100 unit space with the baseline at y = 0, already
 * flipped into SVG's y-down axis. \`len\` is the exact getTotalLength() of that
 * glyph's outline, measured in Chrome, and drives both stroke-dasharray and the
 * per-letter duration so long letters take longer to write — the same rule the
 * reference applies at runtime.
 */\n\n`

const out =
  header +
  'export type ScriptGlyph = { d: string; len: number }\n' +
  'export type ScriptWord = { width: number; glyphs: ScriptGlyph[] }\n' +
  'export type ScriptLine = { text: string; bbox: number[]; words: ScriptWord[] }\n' +
  'export type DisplayWord = { text: string; bbox: number[]; d: string }\n\n' +
  `export const SCRIPT: Record<string, ScriptLine> = ${JSON.stringify(script)} as const\n\n` +
  `export const DISPLAY: Record<string, DisplayWord> = ${JSON.stringify(display)} as const\n`

fs.writeFileSync('src/preview/naustid/handwriting.ts', out)
const kb = (fs.statSync('src/preview/naustid/handwriting.ts').size / 1024).toFixed(1)
console.log(`wrote src/preview/naustid/handwriting.ts (${kb} KB)`)
for (const [k, v] of Object.entries(script))
  console.log(`  script.${k.padEnd(8)} "${v.text}"  words=${v.words.length} glyphs=${v.words.reduce((n, w) => n + w.glyphs.length, 0)} bbox=[${v.bbox}]`)
for (const [k, v] of Object.entries(display))
  console.log(`  display.${k.padEnd(9)} "${v.text}"  bbox=[${v.bbox}]`)
