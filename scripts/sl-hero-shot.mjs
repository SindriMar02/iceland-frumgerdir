import puppeteer from 'puppeteer-core'
const b = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', userDataDir: '/tmp/sl-qa-profile' })
const p = await b.newPage()
const errors = []
p.on('pageerror', (e) => errors.push(`page: ${e.message}`))
p.on('console', (m) => { if (m.type() === 'error') errors.push(`console: ${m.text().slice(0, 160)}`) })
await p.setViewport({ width: 1440, height: 900 })
await p.evaluateOnNewDocument(() => sessionStorage.setItem('sl_seen', '1'))
await p.goto('http://localhost:5299/preview/svartlodge', { waitUntil: 'domcontentloaded' })
await p.evaluate(() => document.fonts.ready)
await new Promise(r => setTimeout(r, 2400))
await p.screenshot({ path: 'scripts/svartlodge-shots/hero-fixed.png' })
// scroll to the shore band
const H = await p.evaluate(() => document.body.scrollHeight)
await p.evaluate((y) => window.scrollTo(0, y), Math.round(H * 0.78))
await new Promise(r => setTimeout(r, 900))
await p.screenshot({ path: 'scripts/svartlodge-shots/shore-fixed.png' })
await p.setViewport({ width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
await p.evaluate(() => window.scrollTo(0, 0))
await p.reload({ waitUntil: 'domcontentloaded' })
await new Promise(r => setTimeout(r, 2400))
await p.screenshot({ path: 'scripts/svartlodge-shots/hero-fixed-mobile.png' })
console.log(JSON.stringify({ errors }))
await b.close()
