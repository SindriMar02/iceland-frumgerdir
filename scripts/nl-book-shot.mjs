import puppeteer from 'puppeteer-core'
const b = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', userDataDir: '/tmp/nl-bshot' })
const p = await b.newPage()
await p.setViewport({ width: 440, height: 956, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
await p.setUserAgent('Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/18.0 Mobile/15E148 Safari/604.1')
await p.evaluateOnNewDocument(() => sessionStorage.setItem('nl_seen','1'))
await p.goto('http://localhost:5299/preview/nollur', { waitUntil: 'domcontentloaded' })
await new Promise(r => setTimeout(r, 3200))
await p.evaluate(() => { const l=[...document.querySelectorAll('.nl-day')].filter(d=>!d.disabled&&!d.classList.contains('nl-day--out')); l[3]?.click() })
await new Promise(r => setTimeout(r, 300))
await p.evaluate(() => { const l=[...document.querySelectorAll('.nl-day')].filter(d=>!d.disabled&&!d.classList.contains('nl-day--out')); l[7]?.click() })
await new Promise(r => setTimeout(r, 400))
const el = await p.$('#book')
await el.screenshot({ path: 'scripts/nollur-shots/book-section.png' })
console.log('ok')
await b.close()
